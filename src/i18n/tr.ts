export const monthNames = tr.monthNames.split(",");

export function formatMonthYear(year: number, month: number): string {
  return `${monthNames[month - 1]} ${year}`;
}

export function formatLongDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${monthNames[m - 1]} ${y}`;
}


export const weekdayLongNames = tr.weekdayLong.split(",");
export const monthShortNames = tr.monthShort.split(",");

export function formatShortDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${monthShortNames[m - 1]} ${y}`;
}

export function formatWeekdayLong(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  const utc = new Date(Date.UTC(y, m - 1, d));
  const weekday = weekdayLongNames[utc.getUTCDay()];
  return `${weekday}, ${d} ${monthNames[m - 1]} ${y}`;
}
